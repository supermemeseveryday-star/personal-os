export function translate(language: Language, text: string): string {
  return language === "zh" ? (zh[text] ?? text) : text;
}

export function durationText(language: Language, value: number): string {
  const n = Math.max(0, Math.round(value));
  if (language === "zh")
    return n >= 60 ? `${Math.floor(n / 60)}小时${n % 60 ? `${n % 60}分钟` : ""}` : `${n}分钟`;
  return n >= 60 ? `${Math.floor(n / 60)}h ${String(n % 60).padStart(2, "0")}m` : `${n}m`;
}
